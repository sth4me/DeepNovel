/**
 * 拼接基础原则与任务提示词：doctrine 在前、任务提示词在后，压缩连续空行。
 * @param {string} doctrine
 * @param {string} taskPrompt
 */
export function composeWritingSystem(doctrine, taskPrompt) {
  const parts = [String(doctrine ?? '').trim(), String(taskPrompt ?? '').trim()].filter(Boolean)
  return parts.join('\n\n').replace(/\n{3,}/g, '\n\n')
}
