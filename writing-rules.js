/** 渲染禁用词清单（提示词/技能正文共用）。 */
export function renderBannedWords() {
  return AI_BANNED_WORDS.join('、')
}

/** 渲染 AI 句式清单。 */
export function renderSentencePatterns() {
  return AI_SENTENCE_PATTERNS.join('；')
}

/** 渲染真人基准清单。 */
export function renderHumanBaseline() {
  return AI_HUMAN_BASELINE.join('；')
}

/** 渲染质检清单为 Markdown 分组文本。 */
export function renderQualityChecklist() {
  const lines = []
  for (const group of QUALITY_CHECKLIST) {
    lines.push(`## ${group.title}`)
    for (const item of group.items) lines.push(`- ${item}`)
    lines.push('')
  }
  return lines.join('\n').trim()
}

