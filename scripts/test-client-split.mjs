// UI 包边界：主 bundle 只带宿主/工具，UI 作为可开关组件行。
import assert from 'node:assert/strict'
import { readFile, access } from 'node:fs/promises'

const rootPackage = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))
const uiPackage = JSON.parse(await readFile(new URL('../ui/package.json', import.meta.url), 'utf8'))
assert.equal(rootPackage.dsh.bundle.patch, './cordis.patch.yml')
assert.equal(rootPackage.dependencies['@sth4me/deepnovel-ui'], 'file:./ui')
assert.ok(!rootPackage.dsh.client, '主包不应带客户端 bundle')
assert.equal(uiPackage.dsh.client.platform, 'web')
assert.equal(uiPackage.dsh.client.immediately, true)
await access(new URL('../ui/client.js', import.meta.url))
await access(new URL('../ui/index.js', import.meta.url))

const client = await readFile(new URL('../ui/client.js', import.meta.url), 'utf8')
assert.ok(client.includes("id: '@sth4me/deepnovel-ui'"))
assert.ok(client.includes("name: 'sidebar.panellist'"))
assert.ok(client.includes("name: 'main'"))
assert.ok(!client.includes('conversation.composer'), '最小 UI 不再嵌入对话输入')
assert.ok(client.includes('pickDirectory'), '项目选择必须调用宿主目录选择器')
assert.ok(client.includes("localStorage.getItem(RECENT_KEY)"), '项目选择应保留最近项目')
assert.ok(client.includes("title: '项目设置'"), '写作台应有项目设置入口')
assert.ok(client.includes('/deepnovel/api/run'), 'AI 任务应优先后台子代理执行')
assert.ok(client.includes('dispatchTask'), '后台执行不可用时必须回退到正常会话发送')
assert.ok(client.includes('TaskDock'), '写作台必须有常驻任务面板')
assert.ok(client.includes('novel_project'), 'AI 任务必须显式打开项目根')
assert.ok(client.includes("label: '构思'"), '核心工作流应包含构思页')
assert.ok(client.includes("label: '资料'"), '写作台应包含资料库页')
assert.ok(client.includes('/deepnovel/api/references/import'), '资料库应支持目录导入')
assert.ok(client.includes('对话内直接改正文'), '项目设置应提供对话内正文开关')
assert.ok(client.includes('search-empty'), '搜索空结果必须是可展开数组元素')
assert.ok(client.includes("row('manuscript', chapter.id"), '文档树必须提供正文入口')
assert.ok(client.includes("kind: chapter.hasManuscript ? 'manuscript' : 'chapter'"), '章节页默认打开正文')
assert.ok(!client.includes("}) : h('div', { style: style.muted }, searchQuery"), '搜索空结果不能直接 spread 单个元素')
assert.ok(client.includes('/deepnovel/api/revisions'), '文档页应能查看修订历史')
assert.ok(client.includes('/deepnovel/api/proposals'), '写作台应能查看待处理提案')
assert.ok(client.includes('deepnovel.v2.draft'), '编辑器应支持本地草稿恢复')
assert.ok(client.includes('setSidebarOpen'), '写作台应能开合侧栏')
assert.ok(client.includes('deepnovel.v2.tasks'), '写作台应保存任务记录')
assert.ok(client.includes('retryTask'), '失败任务应能重试')
assert.ok(client.includes('cancelTask') && client.includes('.cancel?.('), '运行中的任务应能停止')
assert.ok(client.includes("label: '章节'"), '核心工作流应包含章节页')
assert.ok(client.includes('故事方向'), '项目页应能查看故事方向')
assert.ok(client.includes('readiness'), '项目页应展示准备状态（仅提示）')
assert.ok(!client.includes('＋ 新建设定'), '不应保留手动新建设定')
assert.ok(!client.includes('新建人物'), '不应保留手动新建人物')
assert.ok(!client.includes('onCreate'), '写作台不应直接调用手动创建')
assert.ok(client.includes('dispatchTask'), 'AI 任务必须走正常会话派发')
assert.ok(client.includes('connectWorkspace'), 'AI 任务必须创建/复用正常 Workspace 会话')
assert.ok(client.includes('session.prompt'), 'AI 任务必须自动发送到会话')
assert.ok(client.includes('workspaces.create'), '项目未注册工作区时必须创建 Workspace')
assert.ok(client.includes('novel_create'), 'AI 创建必须走原子提案工具')
assert.ok(client.includes('/deepnovel/api/save'), '手动编辑必须自动保存到文件')
assert.ok(client.includes('Ctrl/⌘ + S') || client.includes('Ctrl/⌘+S'), '编辑器应支持保存快捷键')
assert.ok(!client.includes('返回列表'), '文档页不应保留返回列表按钮')
assert.ok(client.includes('告诉 AI 下一步要做什么'), '写作台应有全局 AI 指令入口')
assert.ok(client.includes('runCommand'), '全局指令必须能派发任务')
assert.ok(!client.includes('新建人物'), '不应保留手动新建人物')
assert.ok(!client.includes('＋ 新建设定'), '不应保留手动新建设定')

const patch = await readFile(new URL('../cordis.patch.yml', import.meta.url), 'utf8')
assert.ok(patch.includes("name: '@sth4me/deepnovel'"))
assert.ok(patch.includes("name: '@sth4me/deepnovel-ui'"))
assert.ok(patch.includes("name: '@sth4me/deepnovel/agent'"))

console.log('client split tests passed')
